"""Unprivileged Debian 13 amd64 toolchain from signed, hash-pinned packages."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import subprocess


def run(argv, **kwargs):
    subprocess.run(argv, check=True, **kwargs)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--prefix', type=Path, default=Path('/workspace/toolchain'))
    args = p.parse_args()
    prefix = args.prefix.resolve()
    repo = Path(__file__).resolve().parents[1]
    if prefix == Path('/') or prefix.is_relative_to(repo) or not re.fullmatch(r'/[A-Za-z0-9_.+/-]+', str(prefix)):
        p.error('use a dedicated directory outside the checkout with a plain absolute path')
    if platform.system() != 'Linux' or platform.machine() != 'x86_64':
        p.error('this bootstrap targets Debian 13 amd64')
    release = Path('/etc/os-release').read_text()
    if 'ID=debian' not in release or 'VERSION_ID="13"' not in release:
        p.error('Debian 13 runtime libraries are required; use the documented native prerequisites on other systems')
    marker = prefix / '.xgs116-toolchain'
    if prefix.exists() and any(prefix.iterdir()) and not marker.exists():
        p.error('refusing to mix with an existing unmanaged directory')
    prefix.mkdir(parents=True, exist_ok=True)
    marker.write_text('Debian 13 amd64, XGS116 private toolchain\n')
    apt = prefix / 'apt'
    for directory in ('lists/partial', 'archives/partial', 'parts'):
        (apt / directory).mkdir(parents=True, exist_ok=True)
    (apt / 'empty.conf').write_text('')
    (apt / 'sources.list').write_text('deb [signed-by=/usr/share/keyrings/debian-archive-keyring.gpg] https://deb.debian.org/debian trixie main\n')
    config = apt / 'apt.conf'
    config.write_text(f'''Dir::Etc::main "{apt}/empty.conf";
Dir::Etc::parts "{apt}/parts";
Dir::Etc::sourcelist "{apt}/sources.list";
Dir::Etc::sourceparts "{apt}/parts";
Dir::State "{apt}";
Dir::State::status "/var/lib/dpkg/status";
Dir::Cache "{apt}";
Dir::Cache::archives "{apt}/archives";
Dir::Log "{apt}";
Acquire::Retries "2";
''')
    lock = json.loads(Path(__file__).with_name('debian-toolchain.lock.json').read_text())
    cached = {}
    for deb in (apt / 'archives').glob('*.deb'):
        cached[hashlib.sha256(deb.read_bytes()).hexdigest()] = deb
    needed = [pkg for pkg in lock['packages'] if pkg['sha256'] not in cached]
    if needed:
        env = dict(os.environ, APT_CONFIG=str(config))
        run(['/usr/bin/apt-get', 'update'], env=env)
        run(['/usr/bin/apt-get', 'download'] + [pkg['name'] + '=' + pkg['version'] for pkg in needed],
            cwd=apt / 'archives', env=env)
        for deb in (apt / 'archives').glob('*.deb'):
            cached[hashlib.sha256(deb.read_bytes()).hexdigest()] = deb
    root = prefix / 'root'
    root.mkdir(exist_ok=True)
    for pkg in lock['packages']:
        deb = cached.get(pkg['sha256'])
        if deb is None:
            raise RuntimeError('pinned package absent or checksum differs: ' + pkg['name'])
        run(['dpkg-deb', '-x', str(deb), str(root)])
    bindir = prefix / 'bin'
    bindir.mkdir(exist_ok=True)
    for short, target in [('automake', 'automake-1.17'), ('aclocal', 'aclocal-1.17')]:
        link = bindir / short
        if link.is_symlink():
            link.unlink()
        elif link.exists():
            raise RuntimeError('unexpected local tool: ' + str(link))
        link.symlink_to(root / 'usr/bin' / target)
    m4dir = root / 'usr/share/libtool/m4'
    if not m4dir.exists():
        m4dir.symlink_to('../aclocal')
    auto = prefix / 'autom4te.cfg'
    auto.write_text((root / 'usr/share/autoconf/autom4te.cfg').read_text().replace('/usr/share/autoconf', str(root / 'usr/share/autoconf')))
    (prefix / 'activate.sh').write_text(f'''# Generated by build/setup-linux.py; source before development commands.
export PATH="{bindir}:{root}/usr/bin:{root}/usr/sbin:{root}/usr/lib/llvm-19/bin:$PATH"
export LD_LIBRARY_PATH="{root}/usr/lib/x86_64-linux-gnu${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}"
export ACLOCAL_PATH={root}/usr/share/aclocal
export AC_MACRODIR={root}/usr/share/autoconf
export AUTOMAKE_LIBDIR={root}/usr/share/automake-1.17
export PERL5LIB={root}/usr/share/automake-1.17:{root}/usr/share/autoconf
export LIBTOOLIZE={root}/usr/bin/libtoolize
export LIBTOOL_DATADIR={root}/usr/share/libtool
export ACLOCAL='aclocal --system-acdir={root}/usr/share/aclocal'
export AUTOM4TE={root}/usr/bin/autom4te
export trailer_m4={root}/usr/share/autoconf/autoconf/trailer.m4
export ACLOCAL_AUTOMAKE_DIR={root}/usr/share/aclocal-1.17
export AUTOM4TE_CFG={auto}
export _lt_pkgdatadir={root}/usr/share/libtool
export M4={root}/usr/bin/m4
''')
    print(f'Verified {len(lock["packages"])} packages. Activate: . {prefix}/activate.sh')


if __name__ == '__main__':
    main()
