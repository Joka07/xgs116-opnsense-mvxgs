# One initialization per NPU boot. A failure requires diagnosis, never respawn.
set -eu
DP=${DP:-/opt/xgs116}
case "${1:-}" in
  --apply) ;;
  ""|--dry-run) echo "DRY RUN: validate board/config/modules; isolate switch; start dp_fwd once. No hardware changes."; exit 0 ;;
  *) echo "usage: $0 [--dry-run|--apply]" >&2; exit 2 ;;
esac
[ "$(uname -m)" = aarch64 ] || { echo "Requires the ARM64 NPU" >&2; exit 1; }
[ "$(id -u)" = 0 ] || { echo "Requires root" >&2; exit 1; }
cd "$DP"
# board.conf is written by the operator after per-appliance probing. It is data.
[ -f board.conf ] || { echo "Missing verified board.conf" >&2; exit 1; }
confirmed=$(sed -n 's/^board_confirmed=//p' board.conf)
expected=$(sed -n 's/^dsa_device=//p' board.conf)
[ "$confirmed" = yes ] || { echo "Board profile not confirmed" >&2; exit 1; }
survey=$(sed -n 's/^swop_slot_confirmed=//p' board.conf)
[ "$survey" = yes ] || { echo "NWA+0xf000 SWOP slot must be surveyed on this XGS116 first" >&2; exit 1; }
case "$expected" in ''|*[!0-9]*) echo "Invalid DSA device" >&2; exit 1;; esac
[ "$expected" -le 31 ] || exit 1
# BUILD-INFO subset generated by build script, no shell execution of config.
[ -f build-profile.conf ] || { echo "Missing build-profile.conf" >&2; exit 1; }
built=$(sed -n 's/^dsa_device=//p' build-profile.conf)
[ "$built" = "$expected" ] || { echo "Built DSA target differs from appliance" >&2; exit 1; }
sha256sum -c SHA256SUMS >/dev/null
for name in dp_fwd usfp UMSD_NPU NetAgent; do
  if pidof "$name" >/dev/null 2>&1; then
    echo "Conflicting process $name: stop through its reviewed boot integration first" >&2
    exit 1
  fi
done
# Do not attempt to reconstruct proprietary base initialization here.
for name in mv_armada_ep; do
  grep -q "^$name " /proc/modules || { echo "Required base module $name not initialized by original boot sequence" >&2; exit 1; }
done
# Atomic directory makes repeat attempts fail even after an initialization error.
mkdir /tmp/xgs116-npu-attempted 2>/dev/null || { echo "Already attempted this boot; inspect logs and coordinate host/NPU reboot" >&2; exit 1; }
load_module() {
  name=$1; shift
  grep -q "^$name " /proc/modules && return 0
  candidate="$DP/modules/$(uname -r)/$name.ko"
  if [ ! -f "$candidate" ]; then candidate="$DP/modules/$name.ko"; fi
  if [ ! -f "$candidate" ]; then
    candidate=$(find "/lib/modules/$(uname -r)" -name "$name.ko" -type f | head -1)
  fi
  [ -n "$candidate" ] && [ -f "$candidate" ] || { echo "Missing appliance module $name for $(uname -r)" >&2; exit 1; }
  insmod "$candidate" "$@"
  grep -q "^$name " /proc/modules || { echo "Module $name not active" >&2; exit 1; }
}
load_module musdk_cma
load_module mv_dmax2_uio
load_module uio_pdrv_genirq of_id=generic-uio
SW="$DP/switch-init/swmdio.sh"
reg=$(sh "$SW" rd 0x1b 0x1c)
[ "$((reg & 31))" = "$expected" ] || { echo "Live DSA device mismatch" >&2; exit 1; }
ident=$(sh "$SW" rd 0 3)
[ "$((ident & 0xfff0))" = "$((0x1930))" ] || { echo "Unsupported switch identity $ident" >&2; exit 1; }
XGS116_BOARD_CONFIRMED=yes sh "$DP/switch-init/sw-init.sh" --apply
printf '[xgs116] launching once; wait for GIU ready and host handshake; no automatic restart\n'
exec ./dp_fwd -g 2 -i eth0 -c 1 -a 1 -f dp-nmp-config.txt --no-stat
